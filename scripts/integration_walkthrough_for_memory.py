def _alf_env(home: Path) -> dict:
    """Child env with HOME redirected to an isolated dir and JSON stdout forced,
    so the demo never touches the host's ~/.alf and parses cleanly."""
    env = dict(os.environ)
    env["HOME"] = str(home)
    env.pop("ALF_HUMAN", None)
    return env


def _read_memory_records(alf_path: Path) -> list[dict]:
    """Pull every memory record out of a local .alf (a ZIP of `memory/*.jsonl`)."""
    recs: list[dict] = []
    with zipfile.ZipFile(alf_path) as z:
        for name in z.namelist():
            if name.startswith("memory/") and name.endswith(".jsonl"):
                for line in z.read(name).decode().splitlines():
                    if line.strip():
                        recs.append(json.loads(line))
    return recs


def naive_old_chunk_count(content: str, whole_file: bool) -> int:
    """Reproduce the PRE-WP2 splitter for contrast: split on every line starting
    with '## ' (NOT fence-aware), keeping a section whenever its full text —
    heading line included — is non-empty. Back then active-context was the only
    whole-file special case, and an H1-only preamble counted as a record."""
    if whole_file:
        return 1 if content.strip() else 0
    sections, cur = [], []
    for line in content.splitlines():
        if line.startswith("## "):
            if cur and "\n".join(cur).strip():
                sections.append(cur)
            cur = [line]
        else:
            cur.append(line)
    if cur and "\n".join(cur).strip():
        sections.append(cur)
    return len(sections)


def _seed_workspace(ws: Path) -> None:
    (ws / "memory" / "procedures").mkdir(parents=True, exist_ok=True)
    (ws / "memory" / "curated").mkdir(parents=True, exist_ok=True)
    (ws / "SOUL.md").write_text(SOUL_MD, encoding="utf-8")
    (ws / "IDENTITY.md").write_text(IDENTITY_MD, encoding="utf-8")
    for f in DEMO:
        (ws / f["path"]).write_text(f["content"], encoding="utf-8")


def _print_tree(ws: Path) -> None:
    print(f"  {c('yellow', 'Demo workspace')}")
    print(f"    {ws.name}/")
    entries = sorted(ws.rglob("*"), key=lambda p: p.relative_to(ws).as_posix())
    for p in entries:
        rel = p.relative_to(ws).as_posix()
        depth = rel.count("/")
        indent = "    " + "  " * depth
        name = p.name + ("/" if p.is_dir() else "")
        print(f"{indent}{c('dim', name)}")
    print()


