#!/usr/bin/env python3
"""
agent-life Workspace Coverage Walkthrough (WP3 — `alf add`)
==========================================================

Teaches the explicit "track arbitrary workspace files" feature: how an agent
opts a file into sync with `alf add` (ALF never auto-walks/slurps a workspace),
where the whitelist + removal log live (`.alf-include.json` / `.alf-sync-log.md`,
both synced so they travel on restore), and how changes propagate.

Because arbitrary files are opaque bytes the delta format can't carry, a change
to a tracked file makes `alf sync` upload a fresh **snapshot** (a clean,
non-destructive rollover) instead of a delta — while memory-only changes still
ride efficient deltas. Deleting a tracked file prunes it from the whitelist and
appends a note to `.alf-sync-log.md`.

The CLI lifecycle steps drive the REAL `alf` binary against the live service and
verify each effect in Neon + S3. They skip cleanly if `alf` is not available.

Follows the same UX as `integration_walkthrough.py` (banner, steps, pauses,
markdown report).

Prerequisites:
  pip install requests psycopg2-binary boto3 python-dotenv
  A built `alf` on PATH or under target/ (for the CLI lifecycle steps).

Environment (.env or exported): same as integration_walkthrough.py
  API_BASE_URL, API_KEY, NEON_DATABASE_URL, S3_BUCKET_NAME, AWS_REGION

Usage:
  python3 integration_walkthrough_for_workspace.py
  python3 integration_walkthrough_for_workspace.py --no-pause
  python3 integration_walkthrough_for_workspace.py --report workspace_report.md
"""

from __future__ import annotations

import argparse
import io
import json
import os
import subprocess
import sys
import tempfile
import uuid
import zipfile
from pathlib import Path
from typing import Optional

# Reuse clients, UI, connectivity, and report types from the main walkthrough.
_SCRIPT_DIR = Path(__file__).resolve().parent
if str(_SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPT_DIR))

import integration_walkthrough as iw

# ---------------------------------------------------------------------------
# Workspace-coverage agent (must not collide with the other walkthroughs)
# ---------------------------------------------------------------------------

WS_AGENT_ID = uuid.UUID("e2e10000-feed-4000-b000-000000000003")
WS_AGENT_NAME = "E2E Workspace Walkthrough Agent"

INCLUDE_FILE = ".alf-include.json"
SYNC_LOG_FILE = ".alf-sync-log.md"


def _adapt_report_markdown(md: str) -> str:
    return md.replace(
        "agent-life Integration Test Report",
        "agent-life Workspace Coverage Walkthrough Report",
    ).replace(
        "*Generated by `integration_walkthrough.py`*",
        "*Generated by `integration_walkthrough_for_workspace.py`*",
    )


# ---------------------------------------------------------------------------
# CLI lifecycle helpers
# ---------------------------------------------------------------------------


def _alf_env(home: Path) -> dict:
    """A child-process environment with HOME redirected to an isolated dir, so
    the CLI's ~/.alf (config + state + base snapshot) never touches the host."""
    env = dict(os.environ)
    env["HOME"] = str(home)
    env.pop("ALF_HUMAN", None)  # force JSON stdout
    return env


def _write_alf_config(home: Path, cfg: iw.Config) -> None:
    alf_dir = home / ".alf"
    alf_dir.mkdir(parents=True, exist_ok=True)
    (alf_dir / "config.toml").write_text(
        f'[service]\napi_url = "{cfg.api_url}"\napi_key = "{cfg.api_key}"\n\n'
        f'[defaults]\nruntime = "openclaw"\n',
        encoding="utf-8",
    )


def _run_alf(alf: str, home: Path, args: list[str]) -> tuple[subprocess.CompletedProcess, Optional[dict]]:
    proc = subprocess.run(
        [alf, *args],
        capture_output=True,
        text=True,
        env=_alf_env(home),
        timeout=180,
    )
    parsed: Optional[dict] = None
    if proc.stdout.strip():
        try:
            parsed = json.loads(proc.stdout.strip())
        except json.JSONDecodeError:
            parsed = None
    return proc, parsed


def _seed_workspace(ws: Path) -> None:
    (ws / "memory").mkdir(parents=True, exist_ok=True)
    (ws / "SOUL.md").write_text(f"# {WS_AGENT_NAME}\n\nA tidy agent.\n", encoding="utf-8")
    (ws / "MEMORY.md").write_text("## Facts\n\nThe sky is blue.\n", encoding="utf-8")
    (ws / "memory" / "2026-02-01.md").write_text("## Log\n\nStarted up.\n", encoding="utf-8")
    # A pre-existing fixed agent id so DB queries + cleanup target a known UUID.
    (ws / ".alf-agent-id").write_text(str(WS_AGENT_ID) + "\n", encoding="utf-8")


# alf-managed files worth calling out in the tree so the reader notices them.
_TREE_NOTES = {
    INCLUDE_FILE: "tracked-file whitelist (synced)",
    SYNC_LOG_FILE: "removal log (synced, agent-readable)",
    ".alf-agent-id": "stable agent id",
}


def _print_tree(root: Path, title: str) -> None:
    """Render the workspace as an indented tree, flagging alf-managed files, so
    the reader can watch the workspace evolve across the lifecycle."""
    print(f"  {iw.c('yellow', title)}")
    print(f"    {root.name}/")

    def walk(directory: Path, prefix: str) -> None:
        # Directories first, then files; alphabetical within each — the usual
        # `tree` ordering, and deterministic for a reproducible walkthrough.
        children = sorted(directory.iterdir(), key=lambda p: (p.is_file(), p.name.lower()))
        for i, child in enumerate(children):
            last = i == len(children) - 1
            connector = "└── " if last else "├── "
            if child.is_dir():
                print(f"    {prefix}{connector}{child.name}/")
                walk(child, prefix + ("    " if last else "│   "))
            else:
                rel = child.relative_to(root).as_posix()
                note = _TREE_NOTES.get(rel, "")
                suffix = f"  {iw.c('dim', '← ' + note)}" if note else ""
                size = child.stat().st_size
                print(f"    {prefix}{connector}{child.name} {iw.c('dim', f'({size} B)')}{suffix}")

    walk(root, "")
    print()


def _snapshot_count(db: iw.DbClient) -> int:
    row = db.query_one(
        "SELECT count(*) AS n FROM snapshots WHERE agent_id = %s", (str(WS_AGENT_ID),)
    )
    return int(row["n"]) if row else 0


def _delta_count(db: iw.DbClient) -> int:
    row = db.query_one(
        "SELECT count(*) AS n FROM deltas WHERE agent_id = %s", (str(WS_AGENT_ID),)
    )
    return int(row["n"]) if row else 0


def _latest_snapshot_blob(db: iw.DbClient) -> Optional[str]:
    row = db.query_one(
        "SELECT blob_key FROM snapshots WHERE agent_id = %s "
        "ORDER BY sequence DESC, created_at DESC LIMIT 1",
        (str(WS_AGENT_ID),),
    )
    return row["blob_key"] if row else None


def _raw_names_in_blob(s3: iw.S3Client, blob_key: str) -> list[str]:
    obj = s3.s3.get_object(Bucket=s3.bucket, Key=blob_key)
    raw = obj["Body"].read()
    zf = zipfile.ZipFile(io.BytesIO(raw))
    return [n for n in zf.namelist() if n.startswith("raw/openclaw/")]


