def step_concept_opt_in(cfg: iw.Config, report: iw.Report):
    iw.section(1, "Explicit Opt-In (Concept) — `alf add`, not auto-walk")
    iw.explain(
        """
        ALF deliberately does NOT scan a workspace and slurp every file. The
        agent opts each arbitrary file into sync explicitly:

            alf add notes.txt -r openclaw -w <workspace>

        Known files (SOUL.md, IDENTITY.md, memory/…) are always covered. `alf add`
        extends coverage to anything else the agent wants backed up — a report it
        wrote, a CSV it maintains — without the risk of accidentally syncing a
        50 GB dataset or a node_modules tree.

        Two small files in the workspace carry the state, and both are themselves
        synced so they travel on restore:

          • .alf-include.json  — the whitelist/inventory of opted-in files.
          • .alf-sync-log.md   — an append-only log of removals, so the agent can
                                  later answer "what happened to notes.txt?".
        """
    )
    report.add(iw.StepResult("Opt-in model (concept)", True, 0, "alf add vs auto-walk"))
    iw.pause(cfg)


def step_concept_propagation(cfg: iw.Config, report: iw.Report):
    iw.section(2, "How Tracked Changes Propagate (Concept) — re-snapshot")
    iw.explain(
        """
        Memory records ride incremental DELTAS. Arbitrary tracked files are opaque
        bytes the delta format can't carry, so:

          • Change a tracked file (add / edit / delete) → the next `alf sync`
            uploads a fresh SNAPSHOT. The service treats this as a clean,
            non-destructive ROLLOVER: a new base at the current sequence; prior
            snapshots/deltas are retained for point-in-time restore.
          • Change only memory → the next `alf sync` still pushes an efficient
            DELTA.

        Deleting a tracked file is handled before export: `alf sync` prunes it from
        .alf-include.json and appends a note to .alf-sync-log.md, then re-snapshots
        (so the restored snapshot simply omits the file).
        """
    )
    report.add(iw.StepResult("Propagation (concept)", True, 0, "re-snapshot vs delta"))
    iw.pause(cfg)


