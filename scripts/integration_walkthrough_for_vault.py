def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--no-pause",
        action="store_true",
        help="Run without interactive pauses (for CI)",
    )
    parser.add_argument(
        "--report",
        type=str,
        default="integration_vault_report.md",
        help="Output path for the markdown report",
    )
    args = parser.parse_args()

    cfg = iw.Config.from_env(interactive=not args.no_pause)
    api = iw.ApiClient(cfg)
    db = iw.DbClient(cfg)
    s3 = iw.S3Client(cfg)

    report = iw.Report()
    db_host = cfg.db_url.split("@")[-1].split("/")[0] if "@" in cfg.db_url else "?"
    report.config_summary = {
        "api_url": cfg.api_url,
        "s3_bucket": cfg.s3_bucket,
        "db_host": db_host,
    }

    iw.banner("agent-life Vault Integration Walkthrough")
    print(f"  API:      {cfg.api_url}")
    print(f"  S3:       {cfg.s3_bucket}")
    print(f"  DB:       {db_host}")
    print(f"  Agent ID: {VAULT_AGENT_ID}")
    print(f"  Mode:     {'interactive' if cfg.interactive else 'batch'}")
    print()

    if cfg.interactive:
        print(
            iw.c(
                "dim",
                "  This walkthrough explains the vault and uploads a snapshot with "
                "Layer 4 credentials.",
            )
        )
        print(iw.c("dim", "  Press Enter at each prompt to continue, or Ctrl-C to abort."))
        iw.pause(cfg, "Press Enter to begin...")

    try:
        # ctx=None: the CLI lane is exercised later by the parity/self-heal
        # section; here we only need API / Neon / S3 connectivity.
        iw.step_connectivity(cfg, None, api, db, s3, report)
        step_vault_zero_knowledge(cfg, report)
        step_on_disk_layout(cfg, report)
        step_create_vault_agent(cfg, api, db, report)
        upload_body = step_upload_vault_snapshot(cfg, api, db, s3, report)
        if upload_body:
            step_inspect_s3_archive(cfg, s3, report, upload_body)
        step_surgical_delete_concept(cfg, report)
        step_optional_alf_vault_list(cfg, report)
        step_dry_run_upload_preview(cfg, report)
        step_vault_parity_selfheal(cfg, api, report)
        step_cleanup_vault_agent(cfg, api, db, s3, report)

    except KeyboardInterrupt:
        print(f"\n\n  {iw.c('yellow', 'Interrupted by user.')}")
        print(f"  {iw.c('yellow', f'Agent {VAULT_AGENT_ID} may need manual cleanup.')}")
        report.add(iw.StepResult("Interrupted", False, 0, error="KeyboardInterrupt"))

    iw.banner("Report")
    md = _adapt_report_markdown(report.to_markdown())
    report_path = Path(args.report)
    report_path.write_text(md, encoding="utf-8")
    print(f"  Report written to: {report_path.resolve()}")
    print()

    passed = sum(1 for s in report.steps if s.passed)
    total = len(report.steps)
    total_ms = sum(s.duration_ms for s in report.steps)
    color = "green" if passed == total else "red"
    print(f"  {iw.c(color, f'{passed}/{total} steps passed')}  ({total_ms:.0f} ms total)")
    print()

    sys.exit(0 if passed == total else 1)


if __name__ == "__main__":
    main()
