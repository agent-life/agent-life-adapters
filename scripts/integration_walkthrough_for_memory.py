#!/usr/bin/env python3
"""
agent-life Memory Types & Chunking Walkthrough (WP2 — source-handler table)
==========================================================================

Teaches how the OpenClaw adapter turns workspace Markdown into ALF memory
records: a declarative, path-aware *source-handler table* decides each file's
`memory_type`, `namespace`, and chunking strategy. Two strategies do the work:

  • OneRecordPerFile — the whole file is one record (procedures, curated docs,
    active-context). A procedure no longer shreds into one fragment per heading.
  • SplitByHeading   — one record per `## ` entry (daily journals, MEMORY.md).
    It is fence-aware (a `## ` inside a ``` block is NOT a split point) and
    drops empty-bodied sections — including a leading H1 date header, which used
    to surface as a useless standalone "Saturday, May 23rd, 2026" record.

Unlike the other walkthroughs this one needs NO service, .env, or cloud — memory
chunking is a purely local concern of the adapter. It builds a demo workspace,
runs the REAL `alf export` binary (HOME isolated), reads the resulting `.alf`,
and shows, per file, how many records came out, of what type, and contrasts that
with what the old structure-blind splitter would have produced.

Prerequisites:
  A built `alf` on PATH or under target/{debug,release}/. Nothing else.

Usage:
  python3 integration_walkthrough_for_memory.py
  python3 integration_walkthrough_for_memory.py --no-pause
  python3 integration_walkthrough_for_memory.py --report memory_report.md
"""

