def build_vault_credentials_document(agent_id_str: str) -> dict:
    """Two realistic `alf vault add` records — an email account and a Telegram account.

    The shapes match exactly what `alf vault add` writes into
    `~/.alf/vault/credentials.json`: real-looking AEAD ciphertext, plaintext
    descriptors (service / label / description / tags), and the `alf-vault` tag
    every agent-added record carries.
    """
    now = datetime.now(timezone.utc).isoformat()

    def record(rec_id: str, service: str, label: str, description: str) -> dict:
        return {
            "id": rec_id,
            "agent_id": agent_id_str,
            "service": service,
            "credential_type": "account",
            # Random bytes stand in for a real AEAD blob — without the vault key
            # this is indistinguishable from the secret it protects.
            "encrypted_payload": base64.standard_b64encode(os.urandom(48)).decode("ascii"),
            "encryption": {
                "algorithm": "xchacha20-poly1305",
                "nonce": base64.standard_b64encode(os.urandom(24)).decode("ascii"),
            },
            "created_at": now,
            "label": label,
            "description": description,
            "capabilities_granted": [],
            "tags": ["agent-provisioned", "alf-vault"],
        }

    return {
        "credentials": [
            record(
                "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaa0001",
                "email",
                "kleo@agent-life.run",
                "Agent email account — plaintext metadata, operator-visible.",
            ),
            record(
                "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbb0002",
                "telegram",
                "kleo_bot",
                "Agent Telegram bot account.",
            ),
        ],
        "extra": {},
    }


def build_vault_snapshot_zip(agent_id_str: str) -> bytes:
    """Minimal `.alf` with memory + Layer 4 credentials (same shape the CLI exports)."""
    memories = [
        make_vault_memory(
            "00000000-0000-0000-0000-00000000aa01",
            "Vault walkthrough: memory partitions and credentials layers ship in one archive.",
            "curated",
        ),
    ]
    cred_doc = build_vault_credentials_document(agent_id_str)
    cred_count = len(cred_doc["credentials"])

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        manifest = {
            "alf_version": "1.0.0",
            "created_at": datetime.now(timezone.utc).isoformat(),
            "agent": {
                "id": agent_id_str,
                "name": VAULT_AGENT_NAME,
                "source_runtime": iw.SOURCE_RUNTIME,
            },
            "layers": {
                "memory": {
                    "record_count": len(memories),
                    "index_file": "memory/index.json",
                    "partitions": [
                        {
                            "file": "memory/2026-Q1.jsonl",
                            "from": "2026-01-01",
                            "to": "2026-03-31",
                            "record_count": len(memories),
                            "sealed": False,
                        }
                    ],
                },
                "credentials": {
                    "count": cred_count,
                    "file": "credentials.json",
                },
            },
        }
        zf.writestr("manifest.json", json.dumps(manifest, indent=2))
        zf.writestr(
            "memory/index.json",
            json.dumps({"partitions": manifest["layers"]["memory"]["partitions"]}),
        )
        jsonl = "\n".join(json.dumps(m) for m in memories) + "\n"
        zf.writestr("memory/2026-Q1.jsonl", jsonl)
        zf.writestr("credentials.json", json.dumps(cred_doc, indent=2))
        zf.writestr(
            "raw/openclaw/SOUL.md",
            f"# {VAULT_AGENT_NAME}\n\nPedagogical snapshot including Layer 4.\n",
        )
    return buf.getvalue()


def redact_credentials_for_display(cred_doc: dict) -> dict:
    """Shorten base64 fields for terminal / report output."""

    def short_b64(s: str, keep: int = 28) -> str:
        if len(s) <= keep:
            return s
        return s[:keep] + "…"

    out = json.loads(json.dumps(cred_doc))
    for c in out.get("credentials", []):
        if "encrypted_payload" in c:
            c["encrypted_payload"] = short_b64(c["encrypted_payload"], 32)
        enc = c.get("encryption") or {}
        if enc.get("nonce"):
            enc["nonce"] = short_b64(enc["nonce"], 24)
        c["encryption"] = enc
    return out


