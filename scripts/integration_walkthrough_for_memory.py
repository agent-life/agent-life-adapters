def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--no-pause", action="store_true", help="Run without interactive pauses (for CI)")
    parser.add_argument("--report", type=str, default="integration_memory_report.md",
                        help="Output path for the markdown report")
    args = parser.parse_args()
    interactive = not args.no_pause

    report = Report()
    banner("agent-life Memory Types & Chunking Walkthrough (WP2)")
    print(f"  Subject: OpenClaw source-handler table (local export — no service)")
    print(f"  Mode:    {'interactive' if interactive else 'batch'}\n")
    if interactive:
        print(c("dim", "  Builds a demo workspace, runs `alf export`, and shows how each file chunks."))
        pause(interactive, "Press Enter to begin...")

    try:
        step_concept_table(interactive, report)
        step_concept_chunking(interactive, report)
        step_export_and_illustrate(interactive, report)
    except KeyboardInterrupt:
        print(f"\n\n  {c('yellow', 'Interrupted by user.')}")
        report.add(StepResult("Interrupted", False, error="KeyboardInterrupt"))

    banner("Report")
    Path(args.report).write_text(report.to_markdown(), encoding="utf-8")
    print(f"  Report written to: {Path(args.report).resolve()}\n")

    passed = sum(1 for s in report.steps if s.passed)
    total = len(report.steps)
    color = "green" if passed == total else "red"
    print(f"  {c(color, f'{passed}/{total} steps passed')}\n")
    sys.exit(0 if passed == total else 1)


if __name__ == "__main__":
    main()
