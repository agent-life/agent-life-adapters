def step_concept_table(interactive: bool, report: Report) -> None:
    section(1, "The source-handler table (concept)")
    explain(
        """
        Translating a workspace into ALF is a per-file decision. Instead of one
        blind heuristic, each known location declares how it maps. The OpenClaw
        table (adapter-openclaw/src/memory_parser.rs), first match wins:
        """
    )
    w = max(len(r[0]) for r in HANDLER_TABLE)
    print(f"    {c('bold', 'path'.ljust(w))}   {c('bold', 'memory_type'.ljust(10))} {c('bold', 'namespace'.ljust(14))} chunking")
    for pat, mt, ns, ch in HANDLER_TABLE:
        print(f"    {pat.ljust(w)}   {c('cyan', mt.ljust(10))} {c('yellow', ns.ljust(14))} {ch}")
    print()
    report.add(StepResult("Handler table (concept)", True, f"{len(HANDLER_TABLE)} rows"))
    pause(interactive)


def step_concept_chunking(interactive: bool, report: Report) -> None:
    section(2, "Two chunking strategies (concept)")
    explain(
        """
        OneRecordPerFile — the whole file becomes one record. Used for self-
        contained docs: procedures, curated knowledge, active-context. This is
        the fix for "a procedure shredded into 5–7 fragments".

        SplitByHeading { fence_aware, level } — one record per `## ` heading.
        Used for daily journals and MEMORY.md. Two refinements added in WP2:
          • fence-aware: a `## ` line inside a ``` code block is NOT a split.
          • empty-body drop: a section whose body (content minus its heading
            line) is blank is not emitted — this also drops a leading H1 date
            header, the cause of the spurious "Saturday, May 23rd, 2026" record.

        Round-trip is never at risk: the exact bytes live in raw/openclaw/, so
        what's dropped here only affects the structured, indexed view.
        """
    )
    report.add(StepResult("Chunking strategies (concept)", True, "OneRecordPerFile / SplitByHeading"))
    pause(interactive)


def step_export_and_illustrate(interactive: bool, report: Report) -> None:
    section(3, "Run the real `alf export` and inspect the records")
    explain(
        """
        We seed a demo workspace with one file per behavior, run the actual `alf
        export` binary (HOME isolated, no service), then read the .alf and show
        per file: records produced, type/namespace, and — for contrast — what the
        old structure-blind splitter would have emitted.
        """
    )

    alf = find_alf_binary()
    if not alf:
        ok("`alf` not found on PATH or under target/ — skipping (build with `cargo build`)")
        report.add(StepResult("Export + illustrate", True, "alf not available — skipped"))
        pause(interactive)
        return
    print(f"  Using alf binary: {c('dim', alf)}\n")

    passed = True
    failures: list[str] = []
    try:
        with tempfile.TemporaryDirectory() as home_s, tempfile.TemporaryDirectory() as ws_s:
            home, ws = Path(home_s), Path(ws_s) / "workspace"
            ws.mkdir(parents=True)
            _seed_workspace(ws)
            _print_tree(ws)

            alf_path = Path(ws_s) / "demo.alf"
            proc = subprocess.run(
                [alf, "export", "-r", "openclaw", "-w", str(ws), "-o", str(alf_path)],
                capture_output=True, text=True, env=_alf_env(home), timeout=120,
            )
            if proc.returncode != 0:
                raise RuntimeError(f"alf export failed: {(proc.stderr or proc.stdout)[:300]}")
            summary = json.loads(proc.stdout.strip())
            ok(f"alf export → {summary.get('memory_records')} memory records total\n")

            records = _read_memory_records(alf_path)
            by_file: dict[str, list[dict]] = {}
            for r in records:
                origin = (r.get("source") or {}).get("origin_file")
                by_file.setdefault(origin, []).append(r)

            # Per-file illustration + assertions.
            header = f"    {'file'.ljust(38)} {'old→new'.ljust(9)} {'type'.ljust(10)} namespace"
            print(c("bold", header))
            for f in DEMO:
                got = by_file.get(f["path"], [])
                n_new = len(got)
                # Non-.md files were skipped by the walker before WP2 too, so they
                # never reached the splitter — their honest old count is 0.
                is_md = f["path"].endswith(".md")
                n_old = naive_old_chunk_count(f["content"], f["whole_file_old"]) if is_md else 0
                got_type = got[0]["memory_type"] if got else "—"
                got_ns = got[0]["namespace"] if got else "—"
                arrow = f"{n_old}→{n_new}"
                color = "green" if n_new != n_old else "dim"
                print(f"    {f['path'].ljust(38)} {c(color, arrow.ljust(9))} {c('cyan', got_type.ljust(10))} {c('yellow', got_ns)}")
                print(f"      {c('dim', f['note'])}")
                for r in got:
                    first = r["content"].splitlines()[0] if r["content"].strip() else "(empty)"
                    print(f"        {c('dim', '•')} {first[:72]}")

                # Assertions (this doubles as a functional test).
                if n_new != f["records"]:
                    failures.append(f"{f['path']}: expected {f['records']} records, got {n_new}")
                if got:
                    if got_type != f["mtype"]:
                        failures.append(f"{f['path']}: type {got_type} != {f['mtype']}")
                    if got_ns != f["ns"]:
                        failures.append(f"{f['path']}: namespace {got_ns} != {f['ns']}")
            print()

            # Two headline behaviors, called out explicitly.
            daily = by_file.get("memory/2026-05-23.md", [])
            if any(r["content"].strip() == "# Saturday, May 23rd, 2026" for r in daily):
                failures.append("daily: H1 date header leaked as its own record")
            else:
                ok("Screenshot bug fixed: no standalone '# Saturday, May 23rd, 2026' record")
            if any("## Digest YYYY-MM-DD" in r["content"] for r in daily):
                ok("Fence-aware: the `## Digest` line inside ``` stayed inside its entry, no extra split")
            else:
                failures.append("daily: fenced `## Digest` line was not preserved inside a record")
            proc_recs = by_file.get("memory/procedures/morning-standup.md", [])
            if len(proc_recs) == 1 and proc_recs[0]["content"] == PROCEDURE_MD:
                ok("Procedure collapsed to ONE verbatim record (was 5–7 fragments)")
            else:
                failures.append("procedure: not a single verbatim record")
            if "memory/scratch.txt" not in by_file:
                ok("Non-Markdown scratch.txt produced no structured record (raw-only)")
            else:
                failures.append("scratch.txt unexpectedly produced a memory record")

    except (RuntimeError, AssertionError, KeyError, json.JSONDecodeError) as e:
        passed = False
        fail(str(e))

    if failures:
        passed = False
        for f in failures:
            fail(f)

    report.add(StepResult(
        "Export + illustrate",
        passed,
        "per-file chunking + type verified" if passed else "",
        "; ".join(failures) if failures else "",
    ))
    pause(interactive)


