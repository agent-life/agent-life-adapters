"""
agent-life Vault Integration Walkthrough
=======================================

Teaches new engineers how the zero-knowledge credentials vault fits into the
sync pipeline: what exists **on disk** (workspace + `~/.alf` + runtime vault
key material), what lands **in the cloud** (opaque S3 blob + Postgres metadata
only), and how `credentials.json` travels inside an `.alf` snapshot.

Follows the same UX as `integration_walkthrough.py` (banner, steps, pauses,
markdown report).

Prerequisites:
  pip install requests psycopg2-binary boto3 python-dotenv

Environment (.env or exported): same as integration_walkthrough.py
  API_BASE_URL, API_KEY, NEON_DATABASE_URL, S3_BUCKET_NAME, AWS_REGION

Usage:
  python3 integration_walkthrough_for_vault.py
  python3 integration_walkthrough_for_vault.py --no-pause
  python3 integration_walkthrough_for_vault.py --report vault_report.md
"""

