COLORS = {
    "reset": "\033[0m", "bold": "\033[1m", "dim": "\033[2m", "green": "\033[32m",
    "yellow": "\033[33m", "blue": "\033[34m", "cyan": "\033[36m", "red": "\033[31m",
}


def c(color: str, text: str) -> str:
    return f"{COLORS.get(color, '')}{text}{COLORS['reset']}"


def banner(text: str) -> None:
    print("\n" + c("cyan", "═" * 74))
    print(c("cyan", f"  {text}"))
    print(c("cyan", "═" * 74) + "\n")


def section(num: int, title: str) -> None:
    print("\n" + c("bold", f"── Step {num}: {title} ──") + "\n")


def explain(text: str) -> None:
    for line in textwrap.dedent(text).strip().splitlines():
        print(c("dim", f"  │ {line}"))
    print()


def ok(msg: str) -> None:
    print(f"  {c('green', '✓')} {msg}")


def fail(msg: str) -> None:
    print(f"  {c('red', '✗')} {msg}")


def pause(interactive: bool, prompt: str = "Press Enter to continue...") -> None:
    if interactive:
        input(f"\n  {c('blue', '▸')} {prompt}")
    print()


@dataclass
class StepResult:
    name: str
    passed: bool
    details: str = ""
    error: str = ""


@dataclass
class Report:
    started_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    steps: list[StepResult] = field(default_factory=list)

    def add(self, r: StepResult) -> None:
        self.steps.append(r)

    def to_markdown(self) -> str:
        passed = sum(1 for s in self.steps if s.passed)
        lines = [
            "# agent-life Memory Types & Chunking Walkthrough Report",
            "",
            f"**Date:** {self.started_at.strftime('%Y-%m-%d %H:%M:%S UTC')}  ",
            f"**Scope:** WP2 source-handler table (local `alf export`, no service)  ",
            "",
            "## Summary",
            "",
            "| Metric | Value |",
            "|--------|-------|",
            f"| Steps passed | {passed}/{len(self.steps)} |",
            "",
            "## Steps",
            "",
            "| # | Step | Status | Details |",
            "|---|------|--------|---------|",
        ]
        for i, s in enumerate(self.steps, 1):
            status = "✅" if s.passed else "❌"
            detail = s.details if s.passed else s.error
            lines.append(f"| {i} | {s.name} | {status} | {detail[:90]} |")
        failures = [s for s in self.steps if not s.passed]
        if failures:
            lines += ["", "## Failures", ""]
            for s in failures:
                lines += [f"### {s.name}", "", "```", s.error, "```", ""]
        lines += ["", "---", "*Generated by `integration_walkthrough_for_memory.py`*"]
        return "\n".join(lines)


def find_alf_binary() -> Optional[str]:
    on_path = shutil.which("alf")
    if on_path:
        return on_path
    here = Path(__file__).resolve().parent.parent
    for variant in ("release", "debug"):
        cand = here / "target" / variant / "alf"
        if cand.is_file() and os.access(cand, os.X_OK):
            return str(cand)
    return None


