# CLI lifecycle (drives the real `alf` binary against the live service)
# ---------------------------------------------------------------------------


def step_cli_lifecycle(
    cfg: iw.Config,
    api: iw.ApiClient,
    db: iw.DbClient,
    s3: iw.S3Client,
    report: iw.Report,
):
    iw.section(3, "End-to-End Lifecycle with the Real `alf` CLI")
    iw.explain(
        """
        We drive the actual `alf` binary against the live service, with HOME
        redirected to a temp dir (isolated config + state). Sequence:

          1. first  `alf sync`  → snapshot (registers the agent)
          2. `alf add report.md` + `alf sync` → RE-SNAPSHOT (tracked file added)
          3. edit MEMORY.md + `alf sync` → DELTA (memory-only change)
          4. delete report.md + `alf sync` → prune + log + RE-SNAPSHOT

        Each effect is verified in Neon (snapshot/delta rows) and S3 (the blob's
        raw/openclaw/ contents). Skips cleanly if `alf` is unavailable.
        """
    )

    alf = iw.find_alf_binary()
    if not alf:
        iw.ok("`alf` not found on PATH or in target/ — skipping the CLI lifecycle")
        report.add(iw.StepResult("CLI lifecycle", True, 0, "alf not available"))
        iw.pause(cfg)
        return
    print(f"  Using alf binary: {alf}")

    # Ensure a clean slate: remove any agent left by a prior run so the first
    # `alf sync` is a true first sync (HOME is fresh, so local state is empty).
    api.delete(f"/agents/{WS_AGENT_ID}")

    ok = True
    try:
        with tempfile.TemporaryDirectory() as home_s, tempfile.TemporaryDirectory() as ws_s:
            home = Path(home_s)
            ws = Path(ws_s) / "workspace"
            ws.mkdir(parents=True)
            _write_alf_config(home, cfg)
            _seed_workspace(ws)
            _print_tree(ws, "Workspace — seeded (before first sync)")

            sync_args = ["sync", "-r", "openclaw", "-w", str(ws)]

            # 1) First sync → snapshot.
            proc, res = _run_alf(alf, home, sync_args)
            if proc.returncode != 0 or not res:
                raise RuntimeError(
                    f"first sync failed: {(proc.stderr or proc.stdout)[:300]}"
                )
            iw.ok(f"first sync → sequence {res.get('sequence')}, delta={res.get('delta')}")
            assert res.get("delta") is False, "first sync must be a snapshot"
            assert _snapshot_count(db) == 1, "expected exactly one snapshot after first sync"
            iw.ok(f"Neon: {_snapshot_count(db)} snapshot, {_delta_count(db)} deltas")
            _print_tree(ws, "Workspace — after first sync (unchanged; .alf-agent-id present)")

            # 2) alf add + sync → re-snapshot.
            (ws / "report.md").write_text("# Q1 Report\n\nNumbers go up.\n", encoding="utf-8")
            proc, res = _run_alf(alf, home, ["add", "report.md", "-r", "openclaw", "-w", str(ws)])
            if proc.returncode != 0:
                raise RuntimeError(f"alf add failed: {(proc.stderr or proc.stdout)[:300]}")
            iw.ok("alf add report.md")
            include = json.loads((ws / INCLUDE_FILE).read_text())
            print(f"    {INCLUDE_FILE}: {[f['path'] for f in include['files']]}")
            _print_tree(ws, "Workspace — after `alf add report.md` (report.md + include list)")

            proc, res = _run_alf(alf, home, sync_args)
            if proc.returncode != 0 or not res:
                raise RuntimeError(f"sync after add failed: {(proc.stderr or proc.stdout)[:300]}")
            assert res.get("delta") is False, "tracked-file add must re-snapshot, not delta"
            snaps = _snapshot_count(db)
            assert snaps == 2, f"expected a 2nd snapshot after add, got {snaps}"
            iw.ok(f"add → RE-SNAPSHOT (delta={res.get('delta')}); Neon now has {snaps} snapshots")

            blob = _latest_snapshot_blob(db)
            raw_names = _raw_names_in_blob(s3, blob) if blob else []
            assert "raw/openclaw/report.md" in raw_names, "report.md must be in the snapshot"
            assert f"raw/openclaw/{INCLUDE_FILE}" in raw_names, "include list must travel"
            iw.ok("S3: snapshot contains raw/openclaw/report.md and the include list")

            # 3) Memory-only change → delta.
            (ws / "MEMORY.md").write_text(
                "## Facts\n\nThe sky is blue.\n\n## More\n\nGrass is green.\n", encoding="utf-8"
            )
            proc, res = _run_alf(alf, home, sync_args)
            if proc.returncode != 0 or not res:
                raise RuntimeError(f"memory sync failed: {(proc.stderr or proc.stdout)[:300]}")
            assert res.get("delta") is True, "memory-only change must be a delta"
            deltas = _delta_count(db)
            assert deltas == 1, f"expected 1 delta after memory change, got {deltas}"
            iw.ok(
                f"memory-only → DELTA (delta={res.get('delta')}, seq {res.get('sequence')}); "
                f"Neon snapshots still {_snapshot_count(db)}, deltas {deltas}"
            )
            _print_tree(ws, "Workspace — after editing MEMORY.md (MEMORY.md grew; file set unchanged)")

            # 4) Delete tracked file → prune + log + re-snapshot.
            (ws / "report.md").unlink()
            proc, res = _run_alf(alf, home, sync_args)
            if proc.returncode != 0 or not res:
                raise RuntimeError(f"delete sync failed: {(proc.stderr or proc.stdout)[:300]}")
            assert res.get("delta") is False, "removing a tracked file must re-snapshot"
            snaps = _snapshot_count(db)
            assert snaps == 3, f"expected a 3rd snapshot after delete, got {snaps}"
            iw.ok(f"delete → prune + RE-SNAPSHOT; Neon now has {snaps} snapshots")

            include = json.loads((ws / INCLUDE_FILE).read_text())
            assert all(f["path"] != "report.md" for f in include["files"]), "report.md must be pruned"
            iw.ok(f"{INCLUDE_FILE} pruned: report.md no longer tracked")

            log = (ws / SYNC_LOG_FILE).read_text()
            assert "report.md" in log and "removed" in log, "removal must be logged"
            print(f"  {iw.c('yellow', SYNC_LOG_FILE)}:")
            print("    " + "\n    ".join(log.strip().splitlines()))

            blob = _latest_snapshot_blob(db)
            raw_names = _raw_names_in_blob(s3, blob) if blob else []
            assert "raw/openclaw/report.md" not in raw_names, "deleted file must be absent from snapshot"
            iw.ok("S3: latest snapshot no longer contains report.md (restore would omit it)")
            _print_tree(ws, "Workspace — after deleting report.md + sync (pruned; .alf-sync-log.md added)")

    except (RuntimeError, AssertionError, KeyError, json.JSONDecodeError) as e:
        ok = False
        iw.fail(str(e))

    report.add(
        iw.StepResult(
            "CLI lifecycle",
            ok,
            0,
            "add→re-snapshot, memory→delta, delete→prune+log+re-snapshot" if ok else "",
            "" if ok else "see output above",
        )
    )
    iw.pause(cfg)


def step_cleanup(cfg: iw.Config, api: iw.ApiClient, db: iw.DbClient, s3: iw.S3Client, report: iw.Report):
    iw.section(4, "Cleanup — Delete Workspace Walkthrough Agent")
    iw.explain(
        """
        `DELETE /agents/:id` removes the agent, cascades snapshot/delta rows, and
        deletes objects under `{tenant_id}/{agent_id}/` in S3.
        """
    )
    agent_row = db.query_one("SELECT tenant_id FROM agents WHERE id = %s", (str(WS_AGENT_ID),))
    tenant_id = str(agent_row["tenant_id"]) if agent_row else None
    s3_prefix = f"{tenant_id}/{WS_AGENT_ID}/" if tenant_id else None

    r = api.delete(f"/agents/{WS_AGENT_ID}")
    if r.status_code == 200:
        iw.ok(f"Agent deleted (HTTP 200) — {r.json().get('objects_removed', '?')} S3 objects removed")
    elif r.status_code == 404:
        iw.ok("Agent already absent (HTTP 404)")
    else:
        iw.fail(f"Delete failed (HTTP {r.status_code}): {r.text[:200]}")
        report.add(iw.StepResult("Cleanup", False, 0, error=r.text[:200]))
        iw.pause(cfg)
        return

    if s3_prefix:
        remaining = s3.list_objects(s3_prefix)
        if remaining:
            iw.fail(f"S3 still has {len(remaining)} objects under {s3_prefix}")
        else:
            iw.ok("S3 prefix is empty — all blobs removed")

    report.add(iw.StepResult("Cleanup", True, 0, "Removed agent + blobs"))
    iw.pause(cfg)


